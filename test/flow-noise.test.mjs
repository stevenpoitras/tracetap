import assert from "node:assert/strict";
import { test } from "node:test";

import { deriveFlow } from "../dist/flow/derive.js";

const userStep = (stepIndex, message) => ({
  stepIndex,
  role: "user",
  message,
  reasoning: "",
  toolName: "",
  toolInput: "",
  observation: "",
  errored: false,
});

test("user nodes carry the harness-noise verdict the steps payload uses", () => {
  // The Stream grain labelled `<local-command-caveat>` and `/clear` as PROMPT
  // because the flow graph had no way to say otherwise. It now carries the same
  // isNoiseStep verdict /api/session stamps on steps.
  const flow = deriveFlow({
    steps: [
      userStep(
        1,
        "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>",
      ),
      userStep(2, "<command-name>/clear</command-name>"),
      userStep(3, "what are your goals?"),
    ],
  });
  const byStep = Object.fromEntries(flow.nodes.map((n) => [n.stepIndex, n]));
  assert.equal(byStep[1].noise, true);
  assert.equal(byStep[2].noise, true);
  // Absent, not false, on a real ask — keeps the payload small.
  assert.equal("noise" in byStep[3], false);
});

test("empty and placeholder user steps are flagged noise like any harness step", () => {
  const flow = deriveFlow({ steps: [userStep(1, ""), userStep(2, "<block>no content"), userStep(3, "ask")] });
  const byStep = Object.fromEntries(flow.nodes.map((n) => [n.stepIndex, n]));
  assert.equal(byStep[1].noise, true);
  assert.equal(byStep[2].noise, true);
  assert.equal("noise" in byStep[3], false);
});
